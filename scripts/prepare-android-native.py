from pathlib import Path
import re

# Preserve the existing Google sign-in return link.
manifest = Path("android/app/src/main/AndroidManifest.xml")
if not manifest.exists():
    raise SystemExit("AndroidManifest.xml was not generated by Capacitor.")

xml = manifest.read_text(encoding="utf-8")
intent_filter = """
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="tv.masemedia.masenet" android:host="auth" />
            </intent-filter>
"""
if "tv.masemedia.masenet" not in xml:
    marker = "</activity>"
    if marker not in xml:
        raise SystemExit("Could not find the Capacitor MainActivity in AndroidManifest.xml.")
    xml = xml.replace(marker, intent_filter + "\n        " + marker, 1)
    manifest.write_text(xml, encoding="utf-8")

# The Android shell loads the existing live Cloudflare site, not the bundled
# React source. Register a native browser bridge and patch window.open inside
# that remote WebView so its existing Download episode button opens the real
# device browser. The browser owns the download; MaseNet stores no video files.
java_root = Path("android/app/src/main/java")
main_activity = next(java_root.rglob("MainActivity.java"), None)
if main_activity is None:
    raise SystemExit("Could not find the generated MainActivity.java.")

main_text = main_activity.read_text(encoding="utf-8")
package_match = re.search(r"^package\s+([A-Za-z0-9_.]+);", main_text, re.MULTILINE)
if not package_match:
    raise SystemExit("Could not read the MainActivity Java package.")
package_name = package_match.group(1)

main_activity.write_text(f"""package {package_name};

import android.os.Bundle;
import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {{
    @Override
    public void onCreate(Bundle savedInstanceState) {{
        registerPlugin(MaseExternalBrowserPlugin.class);
        super.onCreate(savedInstanceState);
    }}
}}
""", encoding="utf-8")

plugin = r'''package __PACKAGE__;

import android.content.ActivityNotFoundException;
import android.content.Intent;
import android.net.Uri;
import android.webkit.JavascriptInterface;
import android.webkit.WebView;
import android.widget.Toast;

import com.getcapacitor.Plugin;
import com.getcapacitor.WebViewListener;
import com.getcapacitor.annotation.CapacitorPlugin;

@CapacitorPlugin(name = "MaseExternalBrowser")
public class MaseExternalBrowserPlugin extends Plugin {
    private static final String PATCH_SCRIPT =
        "(function(){" +
        "try{localStorage.removeItem('masenet-native-video-downloads-v1')}catch(e){}" +
        "if(window.__maseNetExternalBrowserPatched)return;" +
        "window.__maseNetExternalBrowserPatched=true;" +
        "var originalOpen=window.open;" +
        "var downloadIntent=false;" +
        "document.addEventListener('click',function(event){" +
        "var node=event.target;" +
        "var button=node&&node.closest?node.closest('button'):null;" +
        "if(!button)return;" +
        "var label=String(button.innerText||button.textContent||'').trim().toLowerCase();" +
        "if(button.classList.contains('maseDownloadAction')||label==='download'||label.indexOf('download episode')!==-1){" +
        "downloadIntent=true;" +
        "window.setTimeout(function(){downloadIntent=false;},5000);" +
        "}" +
        "},true);" +
        "function openExternal(url){" +
        "try{var resolved=new URL(String(url),window.location.href);" +
        "if((resolved.protocol==='https:'||resolved.protocol==='http:')&&window.MaseNetExternalBrowser){" +
        "window.MaseNetExternalBrowser.open(resolved.href);return true;" +
        "}}catch(e){}return false;" +
        "}" +
        "window.open=function(url,target,features){" +
        "if(downloadIntent&&String(target||'_blank').toLowerCase()!=='_self'){" +
        "var initial=String(url||'about:blank');" +
        "if(initial==='about:blank'||initial===''){" +
        "return {closed:false,focus:function(){},close:function(){},location:{set href(value){downloadIntent=false;openExternal(value);},get href(){return 'about:blank';}}};" +
        "}" +
        "if(openExternal(initial)){downloadIntent=false;return {closed:false,focus:function(){},close:function(){},location:{href:initial}};}" +
        "}" +
        "return originalOpen.apply(window,arguments);" +
        "};" +
        "})();";

    @Override
    public void load() {
        // Remove private in-app video files left by the retired offline library.
        new Thread(() -> deleteDirectory(new java.io.File(getContext().getFilesDir(), "masenet-downloads")), "MaseNetOfflineCleanup").start();
        getBridge().getWebView().addJavascriptInterface(new ExternalBrowserBridge(), "MaseNetExternalBrowser");
        getBridge().addWebViewListener(new WebViewListener() {
            @Override
            public void onPageLoaded(WebView webView) {
                webView.evaluateJavascript(PATCH_SCRIPT, null);
            }
        });
    }

    private void deleteDirectory(java.io.File file) {
        if (file == null || !file.exists()) return;
        if (file.isDirectory()) {
            java.io.File[] children = file.listFiles();
            if (children != null) {
                for (java.io.File child : children) deleteDirectory(child);
            }
        }
        file.delete();
    }

    public final class ExternalBrowserBridge {
        @JavascriptInterface
        public void open(String rawUrl) {
            try {
                Uri uri = Uri.parse(rawUrl);
                String scheme = uri.getScheme();
                if (!"https".equalsIgnoreCase(scheme) && !"http".equalsIgnoreCase(scheme)) return;
                getActivity().runOnUiThread(() -> {
                    try {
                        Intent intent = new Intent(Intent.ACTION_VIEW, uri);
                        intent.addCategory(Intent.CATEGORY_BROWSABLE);
                        getActivity().startActivity(intent);
                    } catch (ActivityNotFoundException error) {
                        Toast.makeText(getActivity(), "No browser app is available to open this download.", Toast.LENGTH_LONG).show();
                    }
                });
            } catch (Exception ignored) {
                // Ignore malformed or non-web URLs.
            }
        }
    }
}
'''.replace("__PACKAGE__", package_name)
plugin_path = main_activity.parent / "MaseExternalBrowserPlugin.java"
plugin_path.write_text(plugin, encoding="utf-8")

print("Configured Google sign-in deep link and installed a native external-browser bridge for the live website.")
