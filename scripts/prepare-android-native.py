from pathlib import Path
import sys

manifest = Path("android/app/src/main/AndroidManifest.xml")
if not manifest.exists():
    raise SystemExit("AndroidManifest.xml was not generated by Capacitor.")

xml = manifest.read_text(encoding="utf-8")
intent_filter = """
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="tv.masemedia.masenet" android:host="auth" />
            </intent-filter>
"""
if "tv.masemedia.masenet" not in xml:
    marker = "</activity>"
    if marker not in xml:
        raise SystemExit("Could not find the Capacitor MainActivity in AndroidManifest.xml.")
    xml = xml.replace(marker, intent_filter + "\n        " + marker, 1)
    manifest.write_text(xml, encoding="utf-8")
print("Configured the MaseNet Google sign-in return link.")


# Add a native Android DownloadManager bridge. This is a second download path for
# ordinary video files: Android's own download service handles redirects,
# notifications, retries and background transfers outside the WebView.
from pathlib import Path
import re

gradle = Path("android/app/build.gradle")
gradle_text = gradle.read_text(encoding="utf-8") if gradle.exists() else ""
namespace_match = re.search(r'namespace\s+["\']([^"\']+)["\']', gradle_text)
if not namespace_match:
    raise SystemExit("Could not determine the Android application namespace.")
app_namespace = namespace_match.group(1)
source_root = Path("android/app/src/main/java") / Path(*app_namespace.split("."))
source_root.mkdir(parents=True, exist_ok=True)
plugin_file = source_root / "MaseDownloadManagerPlugin.java"
plugin_file.write_text(r'''package APP_NAMESPACE;

import android.app.DownloadManager;
import android.content.Context;
import android.database.Cursor;
import android.net.Uri;
import android.os.Environment;
import android.webkit.URLUtil;
import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.CapacitorPlugin;

@CapacitorPlugin(name = "MaseDownloadManager")
public class MaseDownloadManagerPlugin extends Plugin {
    @PluginMethod
    public void enqueue(PluginCall call) {
        String url = call.getString("url");
        String filename = call.getString("filename");
        String mime = call.getString("mimeType", "video/mp4");
        if (url == null || !url.startsWith("https://") || filename == null || filename.isEmpty()) {
            call.reject("A secure video URL and filename are required.");
            return;
        }
        try {
            DownloadManager.Request request = new DownloadManager.Request(Uri.parse(url));
            request.setTitle(filename);
            request.setDescription("Saving video for offline playback in MaseNet");
            request.setMimeType(mime);
            request.setAllowedOverMetered(true);
            request.setAllowedOverRoaming(false);
            request.setNotificationVisibility(DownloadManager.Request.VISIBILITY_VISIBLE_NOTIFY_COMPLETED);
            request.setDestinationInExternalFilesDir(getContext(), Environment.DIRECTORY_MOVIES, "MaseNet/" + filename);
            DownloadManager manager = (DownloadManager) getContext().getSystemService(Context.DOWNLOAD_SERVICE);
            long id = manager.enqueue(request);
            JSObject result = new JSObject();
            result.put("downloadId", id);
            call.resolve(result);
        } catch (Exception error) {
            call.reject("Android could not start this download: " + error.getMessage(), error);
        }
    }

    @PluginMethod
    public void status(PluginCall call) {
        long id = call.getLong("downloadId", -1L);
        DownloadManager manager = (DownloadManager) getContext().getSystemService(Context.DOWNLOAD_SERVICE);
        Cursor cursor = manager.query(new DownloadManager.Query().setFilterById(id));
        try {
            if (cursor == null || !cursor.moveToFirst()) {
                call.reject("Android download task was not found.");
                return;
            }
            int status = cursor.getInt(cursor.getColumnIndexOrThrow(DownloadManager.COLUMN_STATUS));
            int reason = cursor.getInt(cursor.getColumnIndexOrThrow(DownloadManager.COLUMN_REASON));
            long downloaded = cursor.getLong(cursor.getColumnIndexOrThrow(DownloadManager.COLUMN_BYTES_DOWNLOADED_SO_FAR));
            long total = cursor.getLong(cursor.getColumnIndexOrThrow(DownloadManager.COLUMN_TOTAL_SIZE_BYTES));
            String uri = cursor.getString(cursor.getColumnIndexOrThrow(DownloadManager.COLUMN_LOCAL_URI));
            JSObject result = new JSObject();
            result.put("status", status == DownloadManager.STATUS_SUCCESSFUL ? "completed" :
                status == DownloadManager.STATUS_FAILED ? "failed" :
                status == DownloadManager.STATUS_PAUSED ? "paused" : "running");
            result.put("reason", reason);
            result.put("downloadedBytes", downloaded);
            result.put("totalBytes", total);
            result.put("uri", uri);
            call.resolve(result);
        } catch (Exception error) {
            call.reject("Could not read Android download status: " + error.getMessage(), error);
        } finally {
            if (cursor != null) cursor.close();
        }
    }

    @PluginMethod
    public void remove(PluginCall call) {
        long id = call.getLong("downloadId", -1L);
        DownloadManager manager = (DownloadManager) getContext().getSystemService(Context.DOWNLOAD_SERVICE);
        manager.remove(id);
        call.resolve();
    }
}
'''.replace("APP_NAMESPACE", app_namespace), encoding="utf-8")

main_candidates = list(Path("android/app/src/main").rglob("MainActivity.java")) + list(Path("android/app/src/main").rglob("MainActivity.kt"))
if not main_candidates:
    raise SystemExit("Could not find Capacitor MainActivity to register the download bridge.")
main = main_candidates[0]
main_text = main.read_text(encoding="utf-8")
if "MaseDownloadManagerPlugin" not in main_text:
    if main.suffix == ".java":
        main_text = main_text.replace("import com.getcapacitor.BridgeActivity;", "import com.getcapacitor.BridgeActivity;\nimport " + app_namespace + ".MaseDownloadManagerPlugin;")
        main_text = main_text.replace("extends BridgeActivity {", "extends BridgeActivity {\n    @Override\n    public void onCreate(android.os.Bundle savedInstanceState) {\n        registerPlugin(MaseDownloadManagerPlugin.class);\n        super.onCreate(savedInstanceState);\n    }")
    else:
        main_text = main_text.replace("import com.getcapacitor.BridgeActivity", "import com.getcapacitor.BridgeActivity\nimport " + app_namespace + ".MaseDownloadManagerPlugin")
        main_text = main_text.replace("class MainActivity : BridgeActivity()", "class MainActivity : BridgeActivity() {\n    override fun onCreate(savedInstanceState: android.os.Bundle?) {\n        registerPlugin(MaseDownloadManagerPlugin::class.java)\n        super.onCreate(savedInstanceState)\n    }\n}")
    main.write_text(main_text, encoding="utf-8")
print("Registered MaseNet's native Android DownloadManager fallback.")
